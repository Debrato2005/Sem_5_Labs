__Vectors
	DCD 0X10001000;STACK POINTER
	DCD Reset_Handler;RESET VECTOR
	
	ALIGN
	AREA MYCODE,CODE , READONLY
	ENTRY
	EXPORT Reset_Handler

Reset_Handler
	LDR R0,=SRC ; SOURCE POINTING TO ITS FIRST ELEMENT OF ARRAY
	LDR R1,=SRC +(N-1+S)*4; DESTINATION IS POINTING TO THE LAST ELEMENT
	MOV R2,#N/2
	
L1  LDR R3, [R0]
	LDR R4, [R1]
	STR R4,[R0],#4 ; STORING LAST ELEMENT AND MOVING FORWARD
	STR R3,[R1],#-4; STORING FIRST ELEMENT AND MOVING BACKWARD
	SUBS R2,#1
	BNE L1
	
STOP B STOP
N EQU 10; NO OF ELEMENTS WE DECIDE ACC TO QN
S EQU 0; SHIFT WE DECIDE ACC TO QN

