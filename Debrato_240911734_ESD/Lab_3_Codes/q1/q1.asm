;Write a program to add ten 32 bit numbers stored in code segment and store
;the result in data segment
	AREA RESET,DATA, READONLY
	EXPORT __Vectors

__Vectors
	DCD 0X10001000;STACK POINTER
	DCD Reset_Handler;RESET VECTOR
	
	ALIGN
	AREA MYCODE,CODE , READONLY
	ENTRY
	EXPORT Reset_Handler

Reset_Handler
	LDR R0,=SRC; GETS ADDRESS
	LDR R1,=SUM
	LDR R2,=CARRY
	MOV R3,#10; COUNTER
	
L1	LDR R4,[R0],#4; GETS VALUE AT THE ADDRESS THEN UPDATES USING POST INDEXING
	
	ADDS R5,R4; ADDS THEN UPDATES CARRY, DEF AULT OF R5 IS 0 
	ADC R6,#0; ADD CARRY TO R3
	
	SUBS R3,#1; UPDATES COUNTER
	BNE L1
	
	STR R5,[R1]
	STRB R6,[R2]
	
STOP B STOP
SRC DCD 0x12345678,0x23456789,0x3456789A,0x456789AB,0x56789ABC,0x6789ABCD,0x789ABCDE,0x89ABCDEF,0x9ABCDEF0,0xABCDEF01
	AREA DATASEG, DATA, READWRITE
SUM DCD 0
CARRY DCB 0

	END